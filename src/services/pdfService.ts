  async downloadReport(data: ReportData, filename: string) {
    try {
      const blob = await this.generateMedicalReport(data);
      
      // Create download link for HTML file
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `${filename}.html`;
      a.style.display = 'none';
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
      
      // Also open the report in a new tab for immediate viewing/printing
      const newTab = window.open();
      if (newTab) {
        const htmlContent = await blob.text();
        newTab.document.write(htmlContent);
        newTab.document.close();
      } else {
        // If popup is blocked, show instructions
        const language = data.language || 'es';
        const instructions = language === 'es' 
          ? 'Reporte descargado exitosamente como archivo HTML.\n\n' +
            'Para convertir a PDF:\n' +
            '1. Abre el archivo HTML descargado\n' +
            '2. Presiona Ctrl+P (Cmd+P en Mac)\n' +
            '3. Selecciona "Guardar como PDF"\n' +
            '4. Haz clic en Guardar'
          : 'Report downloaded successfully as HTML file.\n\n' +
            'To convert to PDF:\n' +
            '1. Open the downloaded HTML file\n' +
            '2. Press Ctrl+P (Cmd+P on Mac)\n' +
            '3. Select "Save as PDF"\n' +
            '4. Click Save';
        alert(instructions);
      }
      
      return true;
    } catch (error) {
      console.error('Error generating report:', error);
      return false;
    }
  }

  private formatDate(dateString: string, language: string = 'es'): string {
    const locale = language === 'es' ? 'es-ES' : 'en-US';
    return new Date(dateString).toLocaleDateString(locale, {
      weekday: 'long',
      year: 'numeric',
      month: 'long',
      day: 'numeric'
    });
  }

